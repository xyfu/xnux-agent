// Command notices writes THIRD_PARTY_NOTICES: the licence and NOTICE
// files of every module linked into xnux-agent, and Go's, copied as the
// authors wrote them (thread 0045). The binary embeds it and LICENSE
// (internal/notices); -check fails when either is out of date, so a
// dependency change cannot ship without them.
//
//	go run ./scripts/notices          # rewrite
//	go run ./scripts/notices -check   # CI
package main

import (
	"bytes"
	"flag"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"sort"
	"strings"
)

const self = "github.com/xyfu/xnux-agent"

type module struct{ path, version, dir string }

func main() {
	check := flag.Bool("check", false, "fail if the files are out of date instead of writing them")
	flag.Parse()
	want, err := notices()
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	license, err := os.ReadFile("LICENSE")
	if err != nil {
		fmt.Fprintln(os.Stderr, "notices:", err)
		os.Exit(1)
	}
	files := map[string][]byte{
		"THIRD_PARTY_NOTICES":                  want,
		"internal/notices/THIRD_PARTY_NOTICES": want,
		"internal/notices/LICENSE":             license,
	}
	stale := false
	for _, name := range []string{"THIRD_PARTY_NOTICES", "internal/notices/THIRD_PARTY_NOTICES", "internal/notices/LICENSE"} {
		have, _ := os.ReadFile(name)
		if bytes.Equal(have, files[name]) {
			continue
		}
		if *check {
			fmt.Fprintf(os.Stderr, "notices: %s is out of date; run go run ./scripts/notices\n", name)
			stale = true
			continue
		}
		if err := os.WriteFile(name, files[name], 0o644); err != nil { //nolint:gosec // a licence text, world-readable
			fmt.Fprintln(os.Stderr, "notices:", err)
			os.Exit(1)
		}
	}
	if stale {
		os.Exit(1)
	}
}

// linked lists the modules the release binary links, for Linux.
func linked() ([]module, error) {
	cmd := exec.Command("go", "list", "-deps", "-f", "{{with .Module}}{{.Path}}\t{{.Version}}\t{{.Dir}}{{end}}", "./cmd/xnux-agent")
	cmd.Env = append(os.Environ(), "GOOS=linux", "CGO_ENABLED=0")
	out, err := cmd.Output()
	if err != nil {
		return nil, fmt.Errorf("go list: %w", err)
	}
	seen := map[string]bool{}
	var mods []module
	for _, line := range strings.Split(strings.TrimSpace(string(out)), "\n") {
		f := strings.Split(line, "\t")
		if len(f) != 3 || f[0] == self || seen[f[0]] {
			continue
		}
		seen[f[0]] = true
		mods = append(mods, module{f[0], f[1], f[2]})
	}
	sort.Slice(mods, func(i, j int) bool { return mods[i].path < mods[j].path })
	return mods, nil
}

// legal returns a module's licence and NOTICE files, sorted by name.
func legal(dir string) ([]string, error) {
	entries, err := os.ReadDir(dir)
	if err != nil {
		return nil, err
	}
	var out []string
	for _, e := range entries {
		n := strings.ToUpper(e.Name())
		if !e.IsDir() && (strings.HasPrefix(n, "LICENSE") || strings.HasPrefix(n, "LICENCE") ||
			strings.HasPrefix(n, "COPYING") || strings.HasPrefix(n, "NOTICE")) {
			out = append(out, filepath.Join(dir, e.Name()))
		}
	}
	sort.Strings(out)
	return out, nil
}

func notices() ([]byte, error) {
	mods, err := linked()
	if err != nil {
		return nil, err
	}
	var b bytes.Buffer
	b.WriteString(`Third-party software in xnux-agent

xnux-agent is licensed under the Apache License 2.0 (see LICENSE). Its
release binary includes the software below, each under its own licence,
reproduced here as its authors wrote it. Generated by scripts/notices
from the modules the binary links.

`)
	for _, m := range mods {
		files, err := legal(m.dir)
		if err != nil {
			return nil, fmt.Errorf("%s: %w", m.path, err)
		}
		if len(files) == 0 {
			return nil, fmt.Errorf("%s %s has no licence file", m.path, m.version)
		}
		writeModule(&b, m.path+" "+m.version, files)
	}
	goroot, err := exec.Command("go", "env", "GOROOT").Output()
	if err != nil {
		return nil, fmt.Errorf("go env GOROOT: %w", err)
	}
	writeModule(&b, "Go standard library and runtime", []string{filepath.Join(strings.TrimSpace(string(goroot)), "LICENSE")})
	return b.Bytes(), nil
}

func writeModule(b *bytes.Buffer, title string, files []string) {
	fmt.Fprintf(b, "%s\n%s\n", strings.Repeat("=", 72), title)
	for _, f := range files {
		text, err := os.ReadFile(f) //nolint:gosec // module cache paths from go list
		if err != nil {
			continue
		}
		fmt.Fprintf(b, "%s\n-- %s --\n\n%s\n", strings.Repeat("-", 72), filepath.Base(f), strings.TrimRight(string(text), "\n"))
	}
	b.WriteString("\n")
}
